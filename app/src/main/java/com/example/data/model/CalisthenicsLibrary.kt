object CalisthenicsLibrary {

    private fun listToJson(cues: List<String>): String {
        val array = JSONArray()
        cues.forEach { array.put(it) }
        return array.toString()
    }

    private fun createEx(
        id: String,
        name: String,
        category: String,
        tier: Int,
        sets: Int,
        reps: String,
        isDur: Boolean,
        durSec: Int,
        muscle: String,
        equip: String,
        inst: String,
        cues: List<String>
    ): ExerciseEntity {
        return ExerciseEntity(
            id = id,
            name = name,
            category = category,
            progressionTier = tier,
            targetSets = sets,
            targetRepsOrDuration = reps,
            isDurationBased = isDur,
            defaultDurationSeconds = durSec,
            muscleGroup = muscle,
            equipmentRequired = equip,
            shortInstructions = inst,
            formCuesJson = listToJson(cues)
        )
    }

